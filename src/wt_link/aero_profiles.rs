//! Таблица захардкоженных аэродинамических профилей срыва потока/сваливания
//! для War Thunder (см. план `cuddly-coalescing-llama.md`). Аналог
//! `crate::profiles`/`aircraft_profiles.rs` на MSFS-стороне (матчинг по
//! имени борта → применение конфига), но здесь — не общий конфиг эффектов, а
//! конкретные пороги критического угла атаки для одного борта.
//!
//! v1 содержит РОВНО один борт (Bf 109 F-4) — числа взяты из внешнего
//! реального аэродинамического описания самолёта (критический AoA, скорости
//! сваливания на разной конфигурации закрылков), НЕ из датамайна War Thunder
//! (там есть только скорость сваливания, угла атаки в градусах нет вообще —
//! проверено по исходникам конкурентного проекта TheDR-lul/Tailgunner). Это
//! гипотеза для живой проверки на реальном самолёте, не откалиброванный
//! результат — см. §8 плана.

/// Пороги срыва потока для одного борта.
#[derive(Debug, Clone, Copy)]
pub struct StallProfile {
    /// Варианты нормализованного имени `/indicators.type`, по которым этот
    /// профиль матчится (см. `match_profile`) — сравнение через `contains`,
    /// не точное равенство, чтобы учесть варианты записи техники в API.
    pub name_patterns: &'static [&'static str],
    /// Критический AoA (град) на чистом крыле (закрылки убраны).
    pub clean_stall_aoa_deg: f32,
    /// Диапазон критического AoA (град) при полностью выпущенных закрылках
    /// (посадочная конфигурация) — используется середина диапазона.
    pub landing_stall_aoa_deg: (f32, f32),
    /// Ниже этой приборной скорости (км/ч) эффект всегда молчит — защита от
    /// ложного срабатывания на рулёжке/стоянке, где AoA может быть большим,
    /// но самолёт физически не летит. Специально низкое значение: это ТОЛЬКО
    /// фильтр "стоим на месте", а не гейт по фазе полёта — при 120 км/ч
    /// (старое значение) он гас эффект прямо посреди реального срыва/штопора,
    /// т.к. IAS у Bf109 в срыве закономерно проседает ниже 120 (торможение +
    /// ошибки трубки Пито на больших углах атаки) — живой тест это подтвердил
    /// (эффект то выключался посреди срыва, то не запускался вовсе).
    pub ias_safety_cutoff_kmh: f32,
    /// AoA (град), выше которого начинает учитываться асимметричный
    /// штопор/срыв (экспериментальная часть плана, §5 — не реализована в
    /// этом v1, поле зарезервировано под будущий шаг).
    pub spin_aoa_threshold_deg: f32,
    pub spin_yaw_rate_threshold: f32,
    pub spin_roll_rate_threshold: f32,
}

/// Bf 109 F-4 — первый и пока единственный борт в таблице (см. план, шапка
/// файла). Числа предоставлены пользователем на основе реальных
/// аэродинамических данных самолёта, требуют калибровки по живому тесту.
///
/// `/indicators.type` для War Thunder использует формат
/// `"{семейство}-{номер}{вариант}-{под-вариант}"` (подтверждено реальными
/// записанными сессиями: `"bf-109e-3"`, `"fw-190a-4"`), поэтому после
/// нормализации (`-`/`_` → пробел) буква варианта остаётся приклеена к
/// номеру модели — паттерн должен быть `"bf 109f 4"`, а не `"bf 109 f 4"`.
/// Держим несколько вариантов на случай иного написания идентификатора.
pub const BF_109_F4: StallProfile = StallProfile {
    name_patterns: &["bf 109f 4", "bf 109 f4", "bf 109 f 4", "bf109f4"],
    clean_stall_aoa_deg: 19.9,
    landing_stall_aoa_deg: (15.0, 17.0),
    ias_safety_cutoff_kmh: 40.0,
    spin_aoa_threshold_deg: 17.0,
    spin_yaw_rate_threshold: 0.35,
    spin_roll_rate_threshold: 0.50,
};

const ALL_PROFILES: &[StallProfile] = &[BF_109_F4];

/// Ищет профиль срыва по названию борта (`WtVars::vehicle_type`,
/// `/indicators.type`). Нормализация — lowercase, `-`/`_` → пробел, затем
/// `contains` — тот же приём, что и в MSFS `aircraft_profiles.rs`. Борт вне
/// таблицы → `None`, эффект должен молчать (см. `ammo::AmmoTracker` — тот же
/// принцип "нет данных = не гадаем").
pub fn match_profile(vehicle_type: &str) -> Option<&'static StallProfile> {
    if vehicle_type.is_empty() {
        return None;
    }
    let normalized = vehicle_type.to_lowercase().replace(['-', '_'], " ");
    ALL_PROFILES
        .iter()
        .find(|p| p.name_patterns.iter().any(|pat| normalized.contains(pat)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_known_name_variants() {
        // "bf-109f-4" — реальный формат идентификатора WT (см. комментарий у
        // BF_109_F4). Остальные — варианты написания на случай отличий.
        for name in [
            "bf-109f-4",
            "BF-109F-4",
            "bf_109f_4",
            "bf109f4",
            "Bf 109 F4",
        ] {
            assert!(
                match_profile(name).is_some(),
                "expected match for {name:?}"
            );
        }
    }

    #[test]
    fn does_not_match_other_aircraft() {
        // Реальные идентификаторы из записанных сессий (bf-109e-3,
        // fw-190a-4), плюс соседние варианты Bf 109 F, которые НЕ должны
        // матчить профиль F-4 (F-2/F-3 — другие подварианты того же семейства).
        for name in [
            "fw-190a-4",
            "bf-109e-3",
            "bf-109f-2",
            "bf-109f-1",
            "",
            "spitfire mk ix",
        ] {
            assert!(
                match_profile(name).is_none(),
                "expected no match for {name:?}"
            );
        }
    }
}
